#!/usr/bin/env python3
"""Package the AURA web app into firmware/AuraGlasses/app_index.h.

Gzips app/index.html and generates a 180x180 home-screen icon PNG
(drawn in pure Python — no Pillow needed), both emitted as C arrays.
"""

import gzip
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP_HTML = ROOT / "app" / "index.html"
OUT_HEADER = ROOT / "firmware" / "AuraGlasses" / "app_index.h"

ICON_SIZE = 180
BG = (12, 14, 20)        # app background #0c0e14
RING = (108, 140, 255)   # accent #6c8cff
PUPIL = (232, 236, 244)  # text color #e8ecf4


def make_icon_png() -> bytes:
    """Solid background with a lens ring + pupil — an 'aura' eye."""
    size = ICON_SIZE
    cx = cy = size / 2 - 0.5
    ring_r, ring_w, pupil_r = size * 0.30, size * 0.055, size * 0.10

    rows = []
    for y in range(size):
        row = bytearray([0])  # PNG filter type 0
        for x in range(size):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
            if abs(d - ring_r) <= ring_w:
                px = RING
            elif d <= pupil_r:
                px = PUPIL
            else:
                px = BG
            row += bytes(px)
        rows.append(bytes(row))

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data))
        )

    ihdr = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)  # 8-bit RGB
    idat = zlib.compress(b"".join(rows), 9)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", idat)
        + chunk(b"IEND", b"")
    )


def c_array(name: str, data: bytes) -> str:
    lines = [f"const size_t {name}_len = {len(data)};"]
    lines.append(f"const uint8_t {name}[] = {{")
    for i in range(0, len(data), 20):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i : i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    html = APP_HTML.read_bytes()
    html_gz = gzip.compress(html, 9)
    icon = make_icon_png()

    OUT_HEADER.write_text(
        "// Generated by tools/build_web.py — do not edit.\n"
        "// Source: app/index.html\n"
        "#ifndef AURA_APP_INDEX_H\n"
        "#define AURA_APP_INDEX_H\n\n"
        "#include <stdint.h>\n"
        "#include <stddef.h>\n\n"
        + c_array("app_index_html_gz", html_gz)
        + "\n\n"
        + c_array("aura_icon_png", icon)
        + "\n\n#endif  // AURA_APP_INDEX_H\n"
    )
    print(
        f"app: {len(html)} B -> {len(html_gz)} B gzipped | "
        f"icon: {len(icon)} B | wrote {OUT_HEADER.relative_to(ROOT)}"
    )


if __name__ == "__main__":
    main()
